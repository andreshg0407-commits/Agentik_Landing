// ── Asset provenance ────────────────────────────────────────────────────────────

export type AssetProvenance =
  | "drive_import"       // Imported from Google Drive
  | "foto_estudio"       // Generated by Foto Estudio AI
  | "manual_upload"      // Manually uploaded by operator
  | "external_sync";     // Synced from Shopify / CRM / other

// ── Asset link contract ─────────────────────────────────────────────────────────

/**
 * Contract for linking a visual asset to an inventory reference.
 *
 * The link is established through:
 *   normalizedRefCode → ProductEntity.sku → ProductAssetLink.productId
 *   ProductAssetLink.assetId → GeneratedAsset.id → assetUrl
 *
 * Future Drive import will:
 *   1. Upload file to R2/CDN
 *   2. Create a GeneratedAsset with assetUrl
 *   3. Find or create ProductEntity by normalizedRefCode
 *   4. Create ProductAssetLink with role + provenance
 */
export interface AssetLinkContract {
  /** Normalized reference code (uppercase, trimmed) — identity key */
  normalizedRefCode: string;

  /** Organization scope */
  organizationId:    string;

  /** GeneratedAsset.id */
  assetId:           string;

  /** Role in the product visual hierarchy */
  role:              "hero" | "gallery" | "swatch" | "video" | "document";

  /** Where this asset came from */
  provenance:        AssetProvenance;

  /** Original source URL (Drive URL, upload path, etc.) */
  sourceUrl?:        string;

  /** When this link was created */
  linkedAt:          Date;
}

// ── Biblioteca as visual provider ───────────────────────────────────────────────

/**
 * Contract for Comercial to consume the primary image from Biblioteca.
 *
 * Comercial MUST NOT:
 *   - Copy files to a separate location
 *   - Create a parallel asset registry
 *   - Store asset URLs directly on commercial models
 *
 * Instead, Comercial calls:
 *   getPrimaryAssetUrl(organizationId, refCode) → string | null
 *
 * This function resolves:
 *   refCode → ProductEntity (by sku) → ProductAssetLink (role="hero") → GeneratedAsset.assetUrl
 */
export interface BibliotecaVisualProvider {
  getPrimaryAssetUrl(organizationId: string, refCode: string): Promise<string | null>;
  getAssetCount(organizationId: string, refCode: string): Promise<number>;
}
